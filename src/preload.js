const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  openDialog: () => ipcRenderer.invoke('open-dialog'),
  openFile: (p) => ipcRenderer.invoke('open-file', p),
  saveFile: (args) => ipcRenderer.invoke('save-file', args),
  exportPdf: (args) => ipcRenderer.invoke('export-pdf', args),
  exportPng: (args) => ipcRenderer.invoke('export-png', args),
  printHtml: (args) => ipcRenderer.invoke('print-html', args),
  printRaster: (args) => ipcRenderer.invoke('print-raster', args),
  pickImage: () => ipcRenderer.invoke('pick-image'),
  getRecent: () => ipcRenderer.invoke('get-recent'),
  clearRecent: () => ipcRenderer.invoke('clear-recent'),
  showInFolder: (p) => ipcRenderer.invoke('show-in-folder', p),
  confirm: (args) => ipcRenderer.invoke('confirm', args),
  forceClose: () => ipcRenderer.invoke('force-close'),
  setTitle: (t) => ipcRenderer.invoke('set-title', t),
  takePending: () => ipcRenderer.invoke('take-pending'),
  readWasm: () => ipcRenderer.invoke('read-wasm'),
  pathForFile: (file) => (webUtils && webUtils.getPathForFile ? webUtils.getPathForFile(file) : file.path),
  updateGet: () => ipcRenderer.invoke('update-get'),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateDownload: () => ipcRenderer.invoke('update-download'),
  updateInstall: () => ipcRenderer.invoke('update-install'),
  onUpdateState: (cb) => ipcRenderer.on('update-state', (e, s) => cb(s)),
  termsGet: () => ipcRenderer.invoke('terms-get'),
  termsAccept: () => ipcRenderer.invoke('terms-accept'),
  termsDecline: () => ipcRenderer.invoke('terms-decline'),
  settingsGet: () => ipcRenderer.invoke('settings-get'),
  settingsSet: (patch) => ipcRenderer.invoke('settings-set', patch),
  craftOpen: (p) => ipcRenderer.invoke('craft-open', p),
  craftSave: (args) => ipcRenderer.invoke('craft-save', args),
  officeFonts: (have) => ipcRenderer.invoke('office-fonts', have),
  annotGet: (key) => ipcRenderer.invoke('annot-get', key),
  annotSet: (key, value) => ipcRenderer.invoke('annot-set', key, value),
  saveScreenshot: (args) => ipcRenderer.invoke('save-screenshot', args),
  setMenuMode: (m) => ipcRenderer.invoke('set-menu-mode', m),
  onMenu: (cb) => ipcRenderer.on('menu', (e, cmd) => cb(cmd)),
  onOpenPath: (cb) => ipcRenderer.on('open-path', (e, p) => cb(p)),
});
